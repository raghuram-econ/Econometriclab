import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';

const WORKSPACE_DIR = process.cwd();
const CERT_FILE_PATH = path.join(WORKSPACE_DIR, 'src/constants/certification.ts');

try {
  console.log('Running NIST and Golden certification tests via Jest...');
  
  // Run Jest with VM modules enabled and output a JSON test report
  const cmd = 'node --experimental-vm-modules node_modules/jest/bin/jest.js --json --outputFile=test-results-all.json 2>&1';
  
  let stdout = '';
  try {
    stdout = execSync(cmd, { encoding: 'utf8' });
  } catch (err) {
    // If tests failed, execSync throws but stdout might still contain useful info
    stdout = err.stdout ? err.stdout.toString() : '';
    console.warn('Jest process returned a non-zero exit code or some tests failed.');
  }

  // Read the JSON test results
  const jsonPath = path.join(WORKSPACE_DIR, 'test-results-all.json');
  if (!fs.existsSync(jsonPath)) {
    throw new Error('test-results-all.json was not generated by Jest!');
  }
  
  const results = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  const goldenSuite = results.testResults.find(t => t.name.includes('golden.test'));
  if (!goldenSuite) throw new Error('golden.test.ts results not found.');
  const passed = goldenSuite.assertionResults.filter(a => a.status === 'passed').length;
  const total = goldenSuite.assertionResults.length;
  
  console.log(`Parsed Test Results: ${passed} / ${total} tests passed.`);

  // NIST console output only survives a single-file (in-band) run.
  const nistCmd = 'node --experimental-vm-modules node_modules/jest/bin/jest.js src/lib/econometrics/__tests__/nist.test.ts --coverage=false 2>&1';
  let nistOut = '';
  try {
    nistOut = execSync(nistCmd, { encoding: 'utf8' });
  } catch (err) {
    nistOut = err.stdout ? err.stdout.toString() : '';
  }

  // Parse NIST LRE values from the nistOut stream, tracking per-dataset worsts
  // so the UI can display real measured numbers instead of hardcoded ones.
  const lreValues = [];
  const longleyLREs = [];
  let wampler1LRE = null;
  let wampler2LRE = null;
  const lines = nistOut.split('\n');
  for (const line of lines) {
    // Only parse the Longley table rows (variable name as the first part)
    if (line.includes('|')) {
      const parts = line.split('|').map(s => s.trim());
      if (parts.length >= 5) {
        const varName = parts[0];
        if (['Intercept', 'x1', 'x2', 'x3', 'x4', 'x5', 'x6'].includes(varName)) {
          const coefLRE = parseFloat(parts[3]);
          const seLRE = parseFloat(parts[4]);
          if (!isNaN(coefLRE)) { lreValues.push(coefLRE); longleyLREs.push(coefLRE); }
          if (!isNaN(seLRE)) { lreValues.push(seLRE); longleyLREs.push(seLRE); }
        }
      }
    }

    // Wampler lines: e.g. "Wampler1 worst LRE: 8.97"
    const wamplerMatch = line.match(/Wampler(\d) worst LRE:\s*([\d\.]+)/);
    if (wamplerMatch) {
      const val = parseFloat(wamplerMatch[2]);
      if (!isNaN(val)) {
        lreValues.push(val);
        if (wamplerMatch[1] === '1') wampler1LRE = val;
        if (wamplerMatch[1] === '2') wampler2LRE = val;
      }
    }
  }

  if (lreValues.length === 0) {
    throw new Error('No NIST LRE values could be parsed. Refusing to write an unverified certification constant.');
  }

  const worstLRE = Math.min(...lreValues);
  const longleyWorst = longleyLREs.length > 0 ? Math.min(...longleyLREs) : null;
  const fmt = v => (v === null ? 'null' : Number(v.toFixed(2)));
  console.log(`NIST Worst-case LRE: ${worstLRE.toFixed(4)} (Longley ${fmt(longleyWorst)}, Wampler1 ${fmt(wampler1LRE)}, Wampler2 ${fmt(wampler2LRE)})`);

  // Write updated constants file
  const today = new Date().toISOString().split('T')[0];
  const fileContent = `// Static build-time certification constants for Numerical Certification
// Generated by scripts/certify-constants.js from a real Jest run. Do not edit by hand.
export const CERTIFICATION_CONSTANTS = {
  nistPrecisionLRE: ${Number(worstLRE.toFixed(2))}, // Log Relative Error worst-case across all NIST benchmarks
  nistPrecisionDigits: "${worstLRE.toFixed(2)} digits",
  // Worst-case LRE per NIST dataset, parsed from the same run (null = not measured)
  lrePerDataset: {
    longley: ${fmt(longleyWorst)},
    wampler1: ${fmt(wampler1LRE)},
    wampler2: ${fmt(wampler2LRE)},
  },
  goldenTestsPassed: ${passed},
  goldenTestsTotal: ${total},
  lastCertifiedDate: "${today}",
  doublePrecisionBits: 64,
};
`;

  fs.writeFileSync(CERT_FILE_PATH, fileContent, 'utf8');
  console.log(`Successfully updated certification constants in ${CERT_FILE_PATH}`);
  
  // Clean up temporary results file
  try {
    fs.unlinkSync(jsonPath);
  } catch (e) {
    // Ignore cleanup errors
  }

} catch (error) {
  console.error('Failed to run certify:constants:', error);
  process.exit(1);
}
